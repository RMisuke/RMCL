/// 将生成的类型写入 `src/ipc/types.ts`（相对 src-tauri manifest 目录）。
#[cfg_attr(all(not(debug_assertions), not(test)), allow(dead_code))]
pub fn write_types_file() -> Result<(), String> {
    let content = generate_types()?;
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or_else(|| "No parent dir for src-tauri".to_string())?
        .join("src/ipc");
    std::fs::create_dir_all(&dir).map_err(|e| format!("create_dir_all failed: {e}"))?;
    let path = dir.join("types.ts");
    std::fs::write(&path, content).map_err(|e| format!("write types.ts failed: {e}"))?;
    tracing::info!(path = %path.display(), "TS bindings exported");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// P1-9（旧 P2-15）：只读比较仓库内 types.ts 与最新生成内容。
    /// 不再写盘——`cargo test` 不得改写工作区；types.ts 的再生成由
    /// `main.rs` 启动时的 `write_types_file()` 负责。字段/类型变更后需
    /// 重新生成并提交该文件，本测试才会通过。
    #[test]
    fn test_types_binding_up_to_date() {
        let content = generate_types().expect("generate types");
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("parent dir")
            .join("src/ipc");
        let path = dir.join("types.ts");
        let existing = std::fs::read_to_string(&path).expect("read types.ts");
        assert_eq!(
            existing, content,
            "src/ipc/types.ts 过期：字段/类型变更后需重新生成并提交该文件"
        );
    }
}
